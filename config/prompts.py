DEFAULT_MODE: Final[str] = "assistant"


def get_mode_prompt(mode_id: str) -> str:
    mode = MODES.get(mode_id) or MODES[DEFAULT_MODE]
    return mode["prompt"]


def get_mode_title(mode_id: str) -> str:
    mode = MODES.get(mode_id) or MODES[DEFAULT_MODE]
    return f'{mode["emoji"]} {mode["title"]}'


def list_mode_ids() -> list[str]:
    return list(MODES.keys())
