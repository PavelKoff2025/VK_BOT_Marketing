def get_question(index: int) -> AuditQuestion | None:
    if 0 <= index < len(AUDIT_QUESTIONS):
        return AUDIT_QUESTIONS[index]
    return None


def total_questions() -> int:
    return len(AUDIT_QUESTIONS)


def format_question_message(index: int) -> str:
    question = get_question(index)
    if not question:
        return ""
    total = total_questions()
    return (
        f"🔍 Первичный маркетинг-аудит\n"
        f"Вопрос {question.number} из {total}\n"
        f"Блок: {question.block}\n\n"
        f"{question.text}\n\n"
        f"Зачем спрашиваем: {question.why}"
    )
